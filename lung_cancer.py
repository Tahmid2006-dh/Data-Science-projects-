from sklearn.model_selection import train_test_split
x=lung_cancer.drop(['Level'],axis=1)
y=lung_cancer['Level']
x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.3, random_state=42)

from sklearn.linear_model import LogisticRegression
lr=LogisticRegression()
lr.fit(x_train,y_train)
test_pred=lr.predict(x_test)
#test_pred
train_pred=lr.predict(x_train)

from sklearn.metrics import accuracy_score
accuracy1=accuracy_score(y_test,test_pred)
print(accuracy1)
accuracy2=accuracy_score(y_train,train_pred)
print(accuracy2)

(pd.Series(abs(lr.coef_[0]), index=x_train.columns).plot(kind='barh'))

""">> from the above we can see genetic risk is playin the most role in predicting the level . coughing of blood is also kepping noticable role in predicting the lvel of lung cancer

>>Age is playing the least role
"""

from sklearn.ensemble import RandomForestClassifier
rf = RandomForestClassifier(
    n_estimators=100,
    max_depth=4,
    max_features='sqrt',
    random_state=42,
    min_samples_split=10,
    min_samples_leaf=5
)
rf.fit(x_train,y_train)
test_predict=rf.predict(x_test)
test_predict
train_predict=rf.predict(x_train)

from sklearn.metrics import accuracy_score
accuracy1=accuracy_score(y_test,test_predict)
print(accuracy1)
accuracy2=accuracy_score(y_train,train_predict)
print(accuracy2)

(pd.Series(rf.feature_importances_,index=x_train.columns).plot(kind='barh'))

